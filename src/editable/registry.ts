/**
 * Keeps the Remotion Studio registry in sync with the projects on disk and
 * writes single-project entry points for rendering (so one broken project
 * never blocks rendering another).
 */
import fs from "node:fs";
import path from "node:path";
import { ROOT, P, store } from "../pipeline/store";
import { componentNameFor } from "./codegen";
import { readSceneSpans } from "./ast";

const REGISTRY = () => path.join(ROOT, "src", "video", "generated", "registry.tsx");

type Entry = { id: string; component: string; importPath: string; width: number; height: number; fps: number; durationInFrames: number };

const entryFor = (id: string, fromDir: string): Entry | null => {
  const p = P(id);
  if (!fs.existsSync(p.editable)) return null;
  const meta = store.metadata(id);
  const src = fs.readFileSync(p.editable, "utf8");
  const { totalFrames } = readSceneSpans(src, meta.fps);
  const rel = path.relative(fromDir, p.editable).replace(/\\/g, "/").replace(/\.tsx$/, "");
  return {
    id,
    component: componentNameFor(id),
    importPath: rel.startsWith(".") ? rel : `./${rel}`,
    width: meta.width,
    height: meta.height,
    fps: meta.fps,
    durationInFrames: Math.max(1, totalFrames),
  };
};

const render = (entries: Entry[], header: string) => `${header}
import {Composition, Folder} from "remotion";
${entries.map((e) => `import {${e.component}} from ${JSON.stringify(e.importPath)};`).join("\n")}

export const ProjectCompositions = () => (
  <Folder name="Projects">
${entries
  .map(
    (e) =>
      `    <Composition id=${JSON.stringify(e.id)} component={${e.component}} width={${e.width}} height={${e.height}} fps={${e.fps}} durationInFrames={${e.durationInFrames}} />`,
  )
  .join("\n")}
  </Folder>
);
`;

const HEADER = "// AUTO-GENERATED by `npm run studio` / the pipeline. Lists every project's editable composition.";

export const syncStudioRegistry = () => {
  const file = REGISTRY();
  const entries = store
    .list()
    .map((m) => {
      try {
        return entryFor(m.id, path.dirname(file));
      } catch {
        return null;
      }
    })
    .filter((e): e is Entry => Boolean(e));
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const content = render(entries, HEADER);
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) fs.writeFileSync(file, content);
  return entries;
};

/** Writes .cache/entries/<id>/index.ts registering only this project (plus library compositions). */
export const writeRenderEntry = (id: string) => {
  const dir = path.join(ROOT, ".cache", "entries", id);
  fs.mkdirSync(dir, { recursive: true });
  const e = entryFor(id, dir);
  if (!e) throw new Error(`Project ${id} has no editable composition yet`);
  const libRel = path.relative(dir, path.join(ROOT, "src", "video", "Library")).replace(/\\/g, "/");
  const fontsRel = path.relative(dir, path.join(ROOT, "src", "video", "fonts")).replace(/\\/g, "/");
  fs.writeFileSync(
    path.join(dir, "Root.tsx"),
    render([e], "// Render entry for a single project.") +
      `\nimport {LibraryCompositions} from ${JSON.stringify(libRel)};\nimport {ensureFonts} from ${JSON.stringify(fontsRel)};\nensureFonts();\nexport const RenderRoot = () => (<><ProjectCompositions /><LibraryCompositions /></>);\n`,
  );
  fs.writeFileSync(path.join(dir, "index.ts"), `import {registerRoot} from "remotion";\nimport {RenderRoot} from "./Root";\nregisterRoot(RenderRoot);\n`);
  return { entry: path.join(dir, "index.ts"), composition: e };
};
